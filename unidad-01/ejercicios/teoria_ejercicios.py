'''
Un algoritmo, en términos generales, puede entenderse como un conjunto de instrucciones ordenadas 
que permiten alcanzar un objetivo o resolver un problema. En esencia, son los pasos necesarios para 
llevar a cabo una tarea.


En el contexto de la programación, un algoritmo es el primer paso que desarrollamos al crear 
un programa. Un programa, a su vez, puede describirse como un conjunto de algoritmos organizados
de forma lógica y sistemática para ser interpretados y ejecutados por una computadora.
'''


# Cuantos tipos de lenguaje de programación hay. Enumerarlos y detallar brevemente cada uno.

'''
Los lenguajes de programación se dividen en dos categorías principales: lenguajes de bajo nivel y 
lenguajes de alto nivel.

Lenguajes de Bajo Nivel
Los lenguajes de bajo nivel están estrechamente ligados al hardware de la computadora. 
Esto significa que sus instrucciones ejercen un control directo sobre los componentes físicos del sistema.

Un ejemplo típico de un lenguaje de bajo nivel es el lenguaje ensamblador.

Lenguajes de Alto Nivel
Los lenguajes de alto nivel son más abstractos y están diseñados para ser independientes del hardware.
Esto signifi ca que el mismo código puede ejecutarse en diferentes tipos de computadoras sin necesidad
de modificaciones significativas.

Un ejemplo típico de un lenguaje de alto nivel es el lenguaje Python.
'''



# Detallar las diferencias entre un lenguaje de programación interpretado y uno compilado.

'''
Compilación: El código fuente se traduce completamente antes de su ejecución, generando un archivo binario
(por ejemplo, un archivo .exe en Windows). Este archivo puede distribuirse y ejecutarse sin necesidad del 
código fuente original. El compilador es el programa que realiza esta traducción, permitiendo que el código 
sea ejecutado directamente por la máquina.

Interpretación: El código fuente se traduce línea por línea durante su ejecución. Este método permite una 
mayor flexibilidad, ya que los cambios en el código pueden probarse de inmediato. El intérprete es el 
programa que ejecuta el código directamente, traduciéndolo a medida que se necesita.
'''

